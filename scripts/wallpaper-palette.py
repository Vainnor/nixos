"""Make a base16 palette (dark, flat, readable) that matches a wallpaper.

    python3 wallpaper-palette.py IMAGE [--bg HEX] [--accent HEX] [--accent2 HEX] [--vivid 0.0-1.0]

Prints a theme.nix for assets/wallpapers/<name>/. Without overrides it picks:
  background  the image's darkest common colour, pushed dark enough for text
  accent      the image's most vivid colour (silver for black-and-white images)
  the rest    greys tinted toward the background, and the usual red/orange/
              yellow/green/cyan/blue/purple at a saturation that suits the image
Run by `vx wallpaper add`; edit the result by hand if a colour feels off.
"""

import argparse
import colorsys

from PIL import Image


def hexc(rgb):
    return "".join(f"{round(max(0, min(1, c)) * 255):02X}" for c in rgb)


def rgb_of(h):
    h = h.lstrip("#")
    return tuple(int(h[i : i + 2], 16) / 255 for i in (0, 2, 4))


def hls(h, l, s):
    return hexc(colorsys.hls_to_rgb(h % 1, l, s))


def analyse(path):
    im = Image.open(path).convert("RGB").resize((320, 140))
    q = im.quantize(colors=16, method=Image.Quantize.MEDIANCUT)
    pal = q.getpalette()
    common = []
    for n, i in sorted(q.getcolors(), reverse=True):
        rgb = tuple(c / 255 for c in pal[i * 3 : i * 3 + 3])
        common.append((n, rgb))
    total = sum(n for n, _ in common)
    # Background: the most common colour among the darker half.
    dark = [c for n, c in common if colorsys.rgb_to_hls(*c)[1] < 0.3] or [common[0][1]]
    bg = dark[0]
    # Accent: the most vivid pixels (saturated and not too dark or light).
    def vivid(c):
        h, l, s = colorsys.rgb_to_hls(*c)
        return s * min(l, 1 - l)

    px = sorted((tuple(x / 255 for x in p) for p in getattr(im, "get_flattened_data", im.getdata)()), key=vivid, reverse=True)
    top = px[: max(1, len(px) // 200)]
    acc = tuple(sum(p[i] for p in top) / len(top) for i in range(3))
    colourful = sum(n for n, c in common if colorsys.rgb_to_hls(*c)[2] > 0.25) / total
    return bg, acc, vivid(acc), colourful


def palette(bg, acc, acc2=None, vivid_level=None, exact=False):
    bh, bl, bs = colorsys.rgb_to_hls(*bg)
    ah, al, as_ = colorsys.rgb_to_hls(*acc)
    mono = as_ < 0.12
    tint = 0.0 if bs < 0.05 else min(bs, 0.35)
    base_l = min(max(bl, 0.035), 0.075)  # dark, but never pure black
    v = vivid_level if vivid_level is not None else (0.22 if mono else 0.62)

    def grey(l, s):
        return hls(bh, l, s)

    if exact:
        accent = hexc(acc)  # chosen by hand: keep it as given
    else:
        accent = hls(ah, max(al, 0.7), 0.0 if mono else max(min(as_, 0.85), 0.45))
    if acc2:
        accent2 = acc2
    else:
        accent2 = hls(ah, 0.85, 0.0 if mono else 0.55)
    p = {
        "base00": grey(base_l, tint),
        "base01": grey(base_l + 0.035, tint * 0.9),
        "base02": grey(base_l + 0.075, tint * 0.8),
        "base03": grey(0.45, tint * 0.45),
        "base04": grey(0.62, tint * 0.35),
        "base05": grey(0.85, tint * 0.25),
        "base06": grey(0.91, tint * 0.2),
        "base07": grey(0.96, tint * 0.15),
        "base08": hls(0.0 / 360, 0.66, v),
        "base09": hls(24 / 360, 0.64, v),
        "base0A": hls(42 / 360, 0.64, v),
        "base0B": hls(100 / 360, 0.62, v * 0.8),
        "base0C": hls(180 / 360, 0.6, v * 0.8),
        "base0D": accent,
        "base0E": hls(270 / 360, 0.7, v),
        "base0F": accent2,
    }
    border = hls(bh, base_l + 0.16, tint * 0.6 if not mono else 0)
    return p, border


def render(name, p, border):
    lines = ["# Generated by scripts/wallpaper-palette.py; edit freely.", "{", "  scheme = {"]
    lines.append(f'    scheme = "{name}";')
    lines.append('    author = "vainnor";')
    lines += [f'    {k} = "{v}";' for k, v in p.items()]
    lines += ["  };", "  extra = {", f'    border = "{border}";', f'    accent2 = "{p["base0F"]}";', "  };", "}"]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    a = argparse.ArgumentParser()
    a.add_argument("image")
    a.add_argument("--name", default="wallpaper")
    a.add_argument("--bg")
    a.add_argument("--accent")
    a.add_argument("--accent2")
    a.add_argument("--vivid", type=float)
    o = a.parse_args()
    bg, acc, _, _ = analyse(o.image)
    if o.bg:
        bg = rgb_of(o.bg)
    if o.accent:
        acc = rgb_of(o.accent)
    p, border = palette(
        bg, acc, o.accent2.lstrip("#").upper() if o.accent2 else None, o.vivid, exact=bool(o.accent)
    )
    print(render(o.name, p, border), end="")
